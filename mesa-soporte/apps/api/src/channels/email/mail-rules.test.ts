import { describe, expect, it } from 'vitest';
import {
  applyFilters,
  assertHeaderSafe,
  classifyInbound,
  senderAuthFromHeaders,
  threadIds,
  ticketNumberFromSubject,
} from './mail-rules';

const M365 = 'mx.microsoft.com';

describe('senderAuthFromHeaders', () => {
  it('trusts only the configured server', () => {
    const spoofed = 'mx.microsoft.com.evil; dmarc=pass';
    expect(senderAuthFromHeaders([spoofed], M365)).toBe('none');
    expect(senderAuthFromHeaders(['mx.microsoft.com; dmarc=pass'], null)).toBe('none');
  });

  it('accepts DMARC pass and rejects failures', () => {
    expect(
      senderAuthFromHeaders(
        [
          'spf=pass (sender IP is 1.2.3.4) smtp.mailfrom=cliente.mx; dkim=pass header.d=cliente.mx; dmarc=pass action=none header.from=cliente.mx;',
        ].map((h) => `${M365}; ${h}`),
        M365,
      ),
    ).toBe('pass');
    expect(
      senderAuthFromHeaders(
        [`${M365}; spf=fail smtp.mailfrom=x; dkim=none; dmarc=fail action=quarantine`],
        M365,
      ),
    ).toBe('fail');
    expect(senderAuthFromHeaders([`${M365}; spf=softfail; dkim=pass`], M365)).toBe('fail');
    expect(senderAuthFromHeaders([`${M365}; spf=pass; dkim=pass`], M365)).toBe('pass');
    expect(senderAuthFromHeaders([`${M365}; spf=pass; dkim=none`], M365)).toBe('none');
  });
});

describe('classifyInbound', () => {
  const headers = (h: Record<string, string>) => (n: string) => h[n];
  it('detects automatic messages and bounces', () => {
    expect(
      classifyInbound(headers({ 'auto-submitted': 'auto-replied' }), 'a@b.mx', 'text/plain')
        .autoGenerated,
    ).toBe(true);
    expect(
      classifyInbound(headers({ 'auto-submitted': 'no' }), 'a@b.mx', 'text/plain').autoGenerated,
    ).toBe(false);
    expect(
      classifyInbound(headers({ precedence: 'bulk' }), 'a@b.mx', 'text/plain').autoGenerated,
    ).toBe(true);
    expect(classifyInbound(headers({}), 'MAILER-DAEMON@b.mx', 'text/plain')).toEqual({
      autoGenerated: true,
      bounce: true,
    });
    expect(
      classifyInbound(
        headers({}),
        'x@b.mx',
        'multipart/report; report-type=delivery-status; boundary=x',
      ).bounce,
    ).toBe(true);
  });
});

describe('threading', () => {
  it('extracts the ticket number only with the hook', () => {
    expect(ticketNumberFromSubject('RE: [Ticket#202610170001] Error', 'Ticket#')).toBe(
      '202610170001',
    );
    expect(ticketNumberFromSubject('RE: Ticket 202610170001 Error', 'Ticket#')).toBeNull();
  });

  it('collects message ids', () => {
    expect(threadIds('<a@x>', ['<b@x>', '<a@x>'])).toEqual(['<a@x>', '<b@x>']);
    expect(threadIds(undefined, '<c@x> junk <d@y>')).toEqual(['<c@x>', '<d@y>']);
  });
});

describe('postmaster filters', () => {
  it('applies matching filters in order', () => {
    const h = (n: string) =>
      ({ from: 'alertas@monitor.inncentives.mx', subject: 'ALERTA prod' })[n];
    const set = applyFilters(
      [
        {
          match: [{ header: 'from', operator: 'ends_with', value: '@monitor.inncentives.mx' }],
          set: { priorityId: 'p4', tags: ['monitoreo'] },
        },
        {
          match: [{ header: 'subject', operator: 'contains', value: 'alerta' }],
          set: { tags: ['alerta'] },
        },
        { match: [{ header: 'subject', operator: 'is', value: 'nada' }], set: { ignore: true } },
      ],
      h,
    );
    expect(set).toEqual({ priorityId: 'p4', tags: ['monitoreo', 'alerta'] });
  });

  it('rejects header injection', () => {
    expect(() => assertHeaderSafe('Hola\r\nBcc: x@y')).toThrow();
  });
});
