/**
 * Pure rules for inbound e-mail: sender authentication, loop and bounce
 * detection, thread matching and postmaster filters.
 */

export type SenderAuth = 'pass' | 'fail' | 'none';

/**
 * Reads Authentication-Results headers (RFC 8601) written by a trusted
 * server only (authserv-id). Headers from any other server are ignored,
 * because a sender can add fake ones.
 */
export function senderAuthFromHeaders(
  headers: string[],
  trustedAuthServ: string | null,
): SenderAuth {
  if (!trustedAuthServ) return 'none';
  const trusted = trustedAuthServ.trim().toLowerCase();
  const results = new Map<string, string>();
  for (const raw of headers) {
    const h = raw
      .replace(/\([^)]*\)/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
    const [servPart, ...rest] = h.split(';');
    const authserv = (servPart ?? '').trim().split(' ')[0]?.toLowerCase();
    if (authserv !== trusted) continue;
    for (const part of rest) {
      const m = /^\s*(spf|dkim|dmarc)\s*=\s*([a-z]+)/i.exec(part);
      if (!m) continue;
      const method = m[1]!.toLowerCase();
      const value = m[2]!.toLowerCase();
      // Keep a pass if any signature passed (several DKIM results are common).
      if (results.get(method) !== 'pass') results.set(method, value);
    }
    break; // the topmost trusted header is authoritative
  }
  const dmarc = results.get('dmarc');
  if (dmarc === 'pass') return 'pass';
  if (dmarc && dmarc !== 'none' && dmarc !== 'bestguesspass') return 'fail';
  const spf = results.get('spf');
  const dkim = results.get('dkim');
  if ([spf, dkim].some((v) => v === 'fail' || v === 'softfail' || v === 'permerror')) return 'fail';
  if (dkim === 'pass' && spf === 'pass') return 'pass';
  return 'none';
}

export interface Classification {
  /** Automatic message: never auto-reply to it. */
  autoGenerated: boolean;
  /** Delivery status notification for one of our messages. */
  bounce: boolean;
}

export function classifyInbound(
  h: (name: string) => string | undefined,
  from: string,
  contentType: string,
): Classification {
  const autoSubmitted = h('auto-submitted')?.toLowerCase();
  const precedence = h('precedence')?.toLowerCase();
  const bounce =
    (/multipart\/report/i.test(contentType) &&
      /report-type="?delivery-status/i.test(contentType)) ||
    /^(mailer-daemon|postmaster)@/i.test(from);
  const autoGenerated =
    bounce ||
    (autoSubmitted !== undefined && autoSubmitted !== 'no') ||
    h('x-auto-response-suppress') !== undefined ||
    h('x-autoreply') !== undefined ||
    h('x-autorespond') !== undefined ||
    h('list-id') !== undefined ||
    (precedence !== undefined && ['bulk', 'junk', 'list', 'auto_reply'].includes(precedence));
  return { autoGenerated, bounce };
}

/** Ticket number from a subject such as "Re: [Ticket#202610170001] …". */
export function ticketNumberFromSubject(subject: string, hook: string): string | null {
  const escaped = hook.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const m = new RegExp(`\\[${escaped}\\s?(\\d{12,16})\\]`, 'i').exec(subject);
  return m ? m[1]! : null;
}

/** Message ids from In-Reply-To and References, normalised with angle brackets. */
export function threadIds(
  inReplyTo: string | undefined,
  references: string | string[] | undefined,
): string[] {
  const refs = Array.isArray(references) ? references.join(' ') : (references ?? '');
  const all = `${inReplyTo ?? ''} ${refs}`.match(/<[^<>\s]{1,250}>/g) ?? [];
  return [...new Set(all)].slice(-50);
}

export interface FilterMatch {
  header: string;
  operator: 'contains' | 'is' | 'starts_with' | 'ends_with';
  value: string;
}

export interface FilterSet {
  groupId?: string;
  priorityId?: string;
  tags?: string[];
  ignore?: boolean;
  spam?: boolean;
}

/** Applies postmaster filters in order; later filters override earlier ones. */
export function applyFilters(
  filters: Array<{ match: FilterMatch[]; set: FilterSet }>,
  h: (name: string) => string | undefined,
): FilterSet {
  const out: FilterSet = {};
  for (const f of filters) {
    const ok =
      f.match.length > 0 &&
      f.match.every((m) => {
        const v = (h(m.header.toLowerCase()) ?? '').toLowerCase();
        const want = m.value.toLowerCase();
        switch (m.operator) {
          case 'is':
            return v === want;
          case 'starts_with':
            return v.startsWith(want);
          case 'ends_with':
            return v.endsWith(want);
          default:
            return v.includes(want);
        }
      });
    if (!ok) continue;
    Object.assign(out, { ...f.set, tags: [...(out.tags ?? []), ...(f.set.tags ?? [])] });
  }
  return out;
}

/** Rejects header values that could inject extra headers. */
export function assertHeaderSafe(value: string): string {
  if (/[\r\n\0]/.test(value)) throw new Error('Invalid header value');
  return value;
}
