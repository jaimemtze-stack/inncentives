import type { Article, Attachment, ObjectAttribute, Prisma } from '@prisma/client';
import { customerVisibleFields } from './custom-fields';

export const ticketDetailInclude = {
  tags: true,
  group: { select: { id: true, name: true, isTriage: true } },
  priority: { select: { id: true, name: true, rank: true } },
  owner: { select: { id: true, name: true } },
  customer: { select: { id: true, name: true, email: true, phone: true, organizationId: true } },
  organization: { select: { id: true, name: true } },
} satisfies Prisma.TicketInclude;

export type TicketDetail = Prisma.TicketGetPayload<{ include: typeof ticketDetailInclude }>;

export function agentTicketDto(t: TicketDetail) {
  return {
    id: t.id,
    number: t.number,
    title: t.title,
    state: t.state,
    channel: t.channel,
    priority: t.priority,
    group: t.group,
    owner: t.owner,
    customer: t.customer,
    organization: t.organization,
    unverifiedFrom: t.unverifiedFrom,
    tags: t.tags.map((x) => x.name).sort(),
    customFields: t.customFields,
    pendingUntil: t.pendingUntil,
    sensitiveData: t.sensitiveData,
    slaId: t.slaId,
    firstResponseDueAt: t.firstResponseDueAt,
    firstResponseAt: t.firstResponseAt,
    updateDueAt: t.updateDueAt,
    solutionDueAt: t.solutionDueAt,
    escalationAt: t.escalationAt,
    slaWarningAt: t.slaWarningAt,
    timeSpentMinutes: t.timeSpentMinutes,
    mergedIntoId: t.mergedIntoId,
    lastCustomerContactAt: t.lastCustomerContactAt,
    lastAgentContactAt: t.lastAgentContactAt,
    createdAt: t.createdAt,
    updatedAt: t.updatedAt,
    solvedAt: t.solvedAt,
    closedAt: t.closedAt,
  };
}

export function customerTicketDto(t: TicketDetail, attrs: ObjectAttribute[]) {
  return {
    id: t.id,
    number: t.number,
    title: t.title,
    state: t.state,
    priority: { name: t.priority.name, rank: t.priority.rank },
    customer: t.customer ? { id: t.customer.id, name: t.customer.name } : null,
    organization: t.organization,
    customFields: customerVisibleFields(attrs, (t.customFields ?? {}) as Record<string, unknown>),
    createdAt: t.createdAt,
    updatedAt: t.updatedAt,
    closedAt: t.closedAt,
  };
}

type ArticleWithRefs = Article & {
  attachments: Attachment[];
  createdBy?: { name: string } | null;
};

/** Rewrites cid: images to the authenticated attachment endpoint. */
function inlineImages(html: string, attachments: Attachment[]): string {
  const byCid = new Map(
    attachments.filter((a) => a.contentId).map((a) => [a.contentId!.replace(/[<>]/g, ''), a]),
  );
  return html.replace(/src="cid:([^"]+)"/g, (m, cid: string) => {
    const a = byCid.get(cid);
    return a && a.scanStatus !== 'infected' ? `src="/api/v1/attachments/${a.id}/inline"` : 'src=""';
  });
}

function attachmentDto(a: Attachment) {
  return {
    id: a.id,
    filename: a.filename,
    size: a.size,
    contentType: a.contentType,
    scanStatus: a.scanStatus,
    inline: a.inline,
  };
}

export function articleDto(a: ArticleWithRefs, audience: 'agent' | 'customer') {
  const attachments = a.attachments.filter((x) => !x.deletedAt);
  const base = {
    id: a.id,
    type: a.type,
    sender: a.sender,
    subject: a.subject,
    bodyHtml: inlineImages(a.bodyHtml, attachments),
    createdAt: a.createdAt,
    authorName: a.createdBy?.name ?? null,
    attachments: attachments.filter((x) => !x.inline).map(attachmentDto),
    redacted: a.redactedAt !== null,
  };
  if (audience === 'customer') return base;
  return {
    ...base,
    internal: a.internal,
    from: a.fromAddress,
    to: a.toAddresses,
    cc: a.ccAddresses,
    senderAuth: a.senderAuth,
    autoGenerated: a.autoGenerated,
    deliveryStatus: a.deliveryStatus,
    deliveryError: a.deliveryError,
    callDirection: a.callDirection,
    callNumber: a.callNumber,
    callDurationSec: a.callDurationSec,
    callOutcome: a.callOutcome,
    sensitiveData: a.sensitiveData,
  };
}
