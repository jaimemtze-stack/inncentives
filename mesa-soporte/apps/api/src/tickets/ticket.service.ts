  async createByAgent(actor: AuthenticatedUser, input: TicketCreateInput): Promise<string> {
    if (!(await this.access.canInGroup(actor, input.groupId, 'create')))
      throw new AppError('forbidden');
    const art = input.article;
    if (art.type === 'web')
      throw new AppError('validation_failed', 'Agents cannot create web articles.');
    await this.assertTimeAccounting(art);
    const attrs = await this.ticketAttributes();
    const customFields = applyCustomFields(attrs, {}, input.customFields ?? undefined, {
      customer: false,
      creating: true,
    });
    const customer = await this.prisma.user.findFirst({
      where: { id: input.customerId, role: 'CUSTOMER', status: 'ACTIVE' },
    });
    if (!customer)
      throw new AppError('validation_failed', 'Unknown customer.', [
        { path: 'customerId', code: 'invalid' },
      ]);
    const inbound = art.type === 'phone' && art.callDirection === 'in';
    const article: NewArticle = {
      type: art.type,
      sender: inbound ? 'customer' : 'agent',
      internal: art.type === 'note' ? art.internal : false,
      body: art.body,
      isHtml: true,
      subject: art.subject ?? input.title,
      from: inbound ? customer.email : null,
      to: art.type === 'email' ? (art.to?.length ? art.to : [customer.email]) : null,
      cc: art.type === 'email' ? (art.cc ?? null) : null,
      callDirection: art.type === 'phone' ? (art.callDirection ?? 'in') : null,
      callNumber: art.callNumber ?? null,
      callDurationSec: art.callDurationSec ?? null,
      callOutcome: art.callOutcome ?? null,
      attachmentIds: art.attachmentIds,
    };
    const state = input.state ?? 'open';
    const draft = {
      title: input.title,
      groupId: input.groupId,
      priorityId: input.priorityId ?? (await this.defaultPriorityId()),
      state,
      ownerId: input.ownerId ?? null,
      customerId: customer.id,
      organizationId: customer.organizationId,
      pendingUntil: input.pendingUntil ?? null,
      customFields,
      tags: input.tags ?? [],
    };
    await this.workflows.enforce('create_agent', null, this.draftSnapshot(draft), {
      currentUserId: actor.id,
    });
    const id = await this.createCore(
      {
        ...draft,
        channel: art.type === 'email' ? 'email' : art.type === 'phone' ? 'phone' : 'agent',
        article,
      },
      { actorId: actor.id },
      { mentions: art.mentions, timeSpent: art.timeSpent, actor },
    );
    return id;
  }

