const MAX_TRIGGER_DEPTH = 3;
const isPending = (s: string) => (PendingStates as readonly string[]).includes(s);

/** Ticket columns a change can touch; each one is recorded in the history. */
export interface TicketPatch {
  title?: string;
  state?: string;
  priorityId?: string;
  groupId?: string;
  ownerId?: string | null;
  customerId?: string | null;
  organizationId?: string | null;
  unverifiedFrom?: string | null;
  pendingUntil?: Date | null;
  customFields?: Record<string, unknown>;
  sensitiveData?: boolean;
}

export interface NewArticle {
  type: string;
  sender: 'customer' | 'agent' | 'system';
  internal: boolean;
  /** HTML (sanitised here) or plain text when isHtml is false. */
  body: string;
  isHtml: boolean;
  subject?: string | null;
  from?: string | null;
  to?: string[] | null;
  cc?: string[] | null;
  messageId?: string | null;
  inReplyTo?: string | null;
  references?: string | null;
  senderAuth?: string | null;
  autoGenerated?: boolean;
  callDirection?: string | null;
  callNumber?: string | null;
  callDurationSec?: number | null;
  callOutcome?: string | null;
  attachmentIds?: string[];
  /** Attachments created by the channel itself (e-mail ingestion). */
  attachmentOwnerId?: string | null;
}

export interface ChangeOptions {
  actorId: string | null;
  depth?: number;
  /** Triggers already fired in this chain (each fires once per chain). */
  fired?: Set<string>;
  /** The inbound message was itself automatic: never auto-reply to it. */
  inboundAutoGenerated?: boolean;
}

interface CreateCore {
  title: string;
  groupId: string;
  priorityId?: string;
  state: string;
  channel: string;
  customerId: string | null;
  unverifiedFrom?: string | null;
  ownerId?: string | null;
  pendingUntil?: Date | null;
  tags?: string[];
  customFields?: Record<string, unknown>;
  article: NewArticle;
}

const HISTORY_FIELDS: Array<keyof TicketPatch> = [
  'title',
  'state',
  'priorityId',
  'groupId',
  'ownerId',
  'customerId',
  'organizationId',
  'pendingUntil',
  'sensitiveData',
];

function historyValue(v: unknown): string | null {
  if (v === null || v === undefined) return null;
  if (v instanceof Date) return v.toISOString();
  const s = typeof v === 'string' ? v : JSON.stringify(v);
  return s.slice(0, 500);
}

