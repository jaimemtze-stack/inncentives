  private async defaultPriorityId(db: Tx = this.prisma): Promise<string> {
    const p =
      (await db.ticketPriority.findFirst({ where: { isDefault: true, active: true } })) ??
      (await db.ticketPriority.findFirst({ where: { active: true }, orderBy: { rank: 'asc' } }));
    if (!p) throw new AppError('internal_error', 'No ticket priorities configured.');
    return p.id;
  }

  /** Checks that every referenced record exists and is usable. */
  private async validatePatch(p: TicketPatch, before: Ticket | null): Promise<void> {
    const bad = (path: string, code = 'invalid'): never => {
      throw new AppError('validation_failed', 'Invalid ticket data.', [{ path, code }]);
    };
    if (
      p.priorityId &&
      !(await this.prisma.ticketPriority.findFirst({ where: { id: p.priorityId, active: true } }))
    )
      bad('priorityId');
    const groupId = p.groupId ?? before?.groupId;
    const group = groupId ? await this.prisma.group.findUnique({ where: { id: groupId } }) : null;
    if (p.groupId && (!group || !group.active)) bad('groupId');
    if (p.ownerId) {
      const owner = await this.prisma.user.findFirst({
        where: { id: p.ownerId, status: 'ACTIVE', role: { in: ['ADMIN', 'AGENT'] } },
        include: { groupAccess: { where: { groupId } } },
      });
      const allowed =
        owner &&
        (owner.role === 'ADMIN' ||
          owner.groupAccess.some((g) => g.levels.some((l) => l === 'full' || l === 'change')));
      if (!allowed) bad('ownerId');
    }
    if (
      p.customerId &&
      !(await this.prisma.user.findFirst({
        where: { id: p.customerId, role: 'CUSTOMER', status: 'ACTIVE' },
      }))
    ) {
      bad('customerId');
    }
    const customerId = p.customerId !== undefined ? p.customerId : before?.customerId;
    if (group && !group.isTriage && !customerId) bad('customerId', 'required');
    const state = p.state ?? before?.state;
    if (before && p.state && isPending(p.state)) {
      const until = p.pendingUntil !== undefined ? p.pendingUntil : before.pendingUntil;
      if (!until) bad('pendingUntil', 'required');
    }
    if (p.pendingUntil && state && !isPending(state)) bad('pendingUntil');
  }

  private draftSnapshot(d: {
    title: string;
    state: string;
    priorityId: string;
    groupId: string;
    ownerId: string | null;
    customerId: string | null;
    organizationId: string | null;
    pendingUntil: Date | null;
    customFields: Record<string, unknown>;
    tags: string[];
  }): TicketSnapshot {
    const now = new Date();
    return {
      number: '',
      title: d.title,
      state: d.state,
      priorityId: d.priorityId,
      groupId: d.groupId,
      ownerId: d.ownerId,
      customerId: d.customerId,
      organizationId: d.organizationId,
      tags: d.tags,
      channel: 'agent',
      pendingUntil: d.pendingUntil,
      escalationAt: null,
      createdAt: now,
      updatedAt: now,
      lastCustomerContactAt: null,
      sensitiveData: false,
      customFields: d.customFields,
    };
  }

  private patchSnapshot(p: TicketPatch): Partial<TicketSnapshot> {
    const out: Partial<TicketSnapshot> = {};
    if (p.title !== undefined) out.title = p.title;
    if (p.state !== undefined) out.state = p.state;
    if (p.priorityId !== undefined) out.priorityId = p.priorityId;
    if (p.groupId !== undefined) out.groupId = p.groupId;
    if (p.ownerId !== undefined) out.ownerId = p.ownerId;
    if (p.customerId !== undefined) out.customerId = p.customerId;
    if (p.pendingUntil !== undefined) out.pendingUntil = p.pendingUntil;
    if (p.customFields !== undefined) out.customFields = p.customFields;
    return out;
  }

  articleSnapshot(a: NewArticle, bodyText: string): ArticleSnapshot {
    return {
      type: a.type,
      sender: a.sender,
      internal: a.internal,
      from: a.from ?? null,
      subject: a.subject ?? null,
      bodyText,
    };
  }

  private emit(
    type: 'ticket.created' | 'ticket.updated' | 'article.created',
    t: Ticket,
    actorId: string | null,
    internal = false,
  ) {
    this.events.emit({
      type,
      ticketId: t.id,
      groupId: t.groupId,
      customerId: t.customerId,
      organizationId: t.organizationId,
      actorId,
      internal,
    });
  }
