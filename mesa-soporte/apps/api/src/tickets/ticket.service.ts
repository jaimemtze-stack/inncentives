  async addArticleByUser(
    actor: AuthenticatedUser,
    id: string,
    input: ArticleCreateInput,
  ): Promise<string> {
    const staff = this.access.isStaff(actor);
    const ticket = await this.access.load(actor, id, staff ? 'change' : 'read', {
      tags: true,
      group: true,
      customer: true,
    });
    if (ticket.state === 'merged')
      throw new AppError('conflict', 'Merged tickets cannot be changed.');
    let article: NewArticle;
    if (staff) {
      if (input.type === 'web')
        throw new AppError('validation_failed', 'Agents cannot create web articles.');
      await this.assertTimeAccounting(input);
      const inbound = input.type === 'phone' && input.callDirection === 'in';
      if (input.type === 'email' && !ticket.customer && !input.to?.length) {
        throw new AppError('validation_failed', 'No recipient.', [
          { path: 'to', code: 'required' },
        ]);
      }
      const hook = await this.settings.get('ticket_hook');
      article = {
        type: input.type,
        sender: inbound ? 'customer' : 'agent',
        internal: input.type === 'note' ? input.internal : false,
        body: input.body,
        isHtml: true,
        subject:
          input.subject ??
          (input.type === 'email' ? `[${hook}${ticket.number}] ${ticket.title}` : null),
        from: inbound ? (ticket.customer?.email ?? null) : null,
        to:
          input.type === 'email' ? (input.to?.length ? input.to : [ticket.customer!.email]) : null,
        cc: input.type === 'email' ? (input.cc ?? null) : null,
        callDirection: input.type === 'phone' ? (input.callDirection ?? 'in') : null,
        callNumber: input.callNumber ?? null,
        callDurationSec: input.callDurationSec ?? null,
        callOutcome: input.callOutcome ?? null,
        attachmentIds: input.attachmentIds,
      };
    } else {
      if (
        input.type !== 'web' ||
        input.internal ||
        input.to ||
        input.cc ||
        input.mentions ||
        input.timeSpent ||
        input.callNumber
      ) {
        throw new AppError('forbidden');
      }
      if (ticket.state === 'closed' && ticket.group.followUp === 'new_ticket') {
        throw new AppError('conflict', 'This ticket is closed. Please open a new ticket.');
      }
      article = {
        type: 'web',
        sender: 'customer',
        internal: false,
        body: input.body,
        isHtml: true,
        subject: ticket.title,
        from: actor.email,
        attachmentIds: input.attachmentIds,
      };
    }
    const result = await this.addArticleCore(
      ticket,
      article,
      { actorId: actor.id },
      { timeSpent: input.timeSpent },
    );
    if (input.mentions?.length) await this.mention(actor, ticket, input.mentions);
    return result;
  }

  /**
   * Adds an article and applies its side effects on the ticket: first
   * response and contact times, automatic state changes (new → open on an
   * agent answer, pending/resolved/closed → open on a customer reply).
   */
  async addArticleCore(
    ticket: TicketWithTags,
    a: NewArticle,
    opts: ChangeOptions,
    extra: { timeSpent?: ArticleCreateInput['timeSpent'] } = {},
  ): Promise<string> {
    const now = new Date();
    const statePatch: TicketPatch = {};
    if (
      a.sender === 'customer' &&
      !a.internal &&
      ['pending_reminder', 'pending_close', 'resolved', 'closed'].includes(ticket.state)
    ) {
      statePatch.state = 'open';
    }
    if (a.sender === 'agent' && !a.internal && ticket.state === 'new') statePatch.state = 'open';
    const article = await this.prisma.$transaction(async (tx) => {
      const article = await this.insertArticle(tx, ticket, a, opts.actorId, now);
      if (extra.timeSpent && opts.actorId)
        await this.addTimeTx(tx, ticket.id, article.id, opts.actorId, extra.timeSpent);
      if (Object.keys(statePatch).length) await this.mutate(tx, ticket, statePatch, opts.actorId);
      return article;
    });
    await this.afterArticle(article.id, a);
    const snap = this.articleSnapshot(a, article.bodyText);
    await this.sla.recompute(ticket.id);
    const after = await this.loadForRules(ticket.id);
    this.emit('article.created', after, opts.actorId, a.internal);
    if (a.sender === 'customer') {
      const recipients = after.ownerId
        ? [after.ownerId]
        : await this.notifications.groupMembers(after.groupId);
      const subs = await this.prisma.subscription.findMany({
        where: { ticketId: ticket.id },
        select: { userId: true },
      });
      await this.notifications.notify(
        [...recipients, ...subs.map((s) => s.userId)],
        after,
        'customer_reply',
        after.title,
        {
          excludeUserId: opts.actorId,
          emailBody: article.bodyText.slice(0, 2000),
        },
      );
    } else if (a.sender === 'agent' && opts.actorId) {
      const subs = await this.prisma.subscription.findMany({
        where: { ticketId: ticket.id },
        select: { userId: true },
      });
      const ids = [...subs.map((s) => s.userId), ...(after.ownerId ? [after.ownerId] : [])];
      await this.notifications.notify(ids, after, 'ticket_updated', after.title, {
        excludeUserId: opts.actorId,
      });
    }
    await this.runTriggers('update', after, ticket, snap, opts);
    return article.id;
  }

  private async insertArticle(
    tx: Tx,
    ticket: Ticket,
    a: NewArticle,
    actorId: string | null,
    now: Date,
  ) {
    const bodyHtml = a.isHtml ? sanitizeHtml(a.body) : textToHtml(a.body);
    const outboundEmail = a.type === 'email' && a.sender !== 'customer' && !a.internal;
    const bodyText = htmlToText(bodyHtml);
    const sensitive = detectText(`${a.subject ?? ''}\n${bodyText}`).length > 0;
    const article = await tx.article.create({
      data: {
        ticketId: ticket.id,
        type: a.type,
        sender: a.sender,
        internal: a.internal,
        fromAddress: a.from ?? null,
        toAddresses: a.to?.join(', ') ?? null,
        ccAddresses: a.cc?.join(', ') ?? null,
        subject: a.subject?.slice(0, 500) ?? null,
        bodyHtml,
        bodyText,
        sensitiveData: sensitive,
        messageId: a.messageId ?? null,
        inReplyTo: a.inReplyTo ?? null,
        references: a.references ?? null,
        senderAuth: a.senderAuth ?? null,
        autoGenerated: a.autoGenerated ?? false,
        deliveryStatus: outboundEmail ? 'queued' : null,
        callDirection: a.callDirection ?? null,
        callNumber: a.callNumber ?? null,
        callDurationSec: a.callDurationSec ?? null,
        callOutcome: a.callOutcome ?? null,
        createdById: actorId,
        createdAt: now,
      },
    });
    if (a.attachmentIds?.length) {
      const owner = a.attachmentOwnerId !== undefined ? a.attachmentOwnerId : actorId;
      const res = await tx.attachment.updateMany({
        where: {
          id: { in: a.attachmentIds },
          uploadedById: owner,
          articleId: null,
          deletedAt: null,
          OR: [{ ticketId: null }, { ticketId: ticket.id }],
        },
        data: { ticketId: ticket.id, articleId: article.id },
      });
      if (res.count !== new Set(a.attachmentIds).size) {
        throw new AppError('validation_failed', 'Unknown attachment.', [
          { path: 'attachmentIds', code: 'invalid' },
        ]);
      }
    }
    const contact: Prisma.TicketUncheckedUpdateInput = sensitive ? { sensitiveData: true } : {};
    if (!a.internal && a.sender === 'customer') contact.lastCustomerContactAt = now;
    if (!a.internal && a.sender === 'agent') {
      contact.lastAgentContactAt = now;
      if (!ticket.firstResponseAt) contact.firstResponseAt = now;
    }
    if (Object.keys(contact).length)
      await tx.ticket.update({ where: { id: ticket.id }, data: contact });
    return article;
  }

